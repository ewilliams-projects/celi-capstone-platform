"""Build the website from web/ and the saved map data in data/snapshots/.

- build_site(): the public page (site/), without the draft neighborhood map.
- build_draft(): the same page plus the neighborhood priority map (output/), never published.
- write_rankings_csv(): the neighborhood table.
"""

import csv
import json
import re
import shutil
from datetime import date
from pathlib import Path
from typing import List

from gasplan.score import ScoredNeighborhood

ROOT = Path(__file__).resolve().parent.parent
WEB = ROOT / "web"
SNAPSHOTS = ROOT / "data" / "snapshots"

# web/index.html marks the draft-only parts (the neighborhood section and its scripts) with
# <!-- NEIGHBORHOODS: ... --> ... <!-- /NEIGHBORHOODS -->; the public page leaves them out.
DRAFT_SECTION = re.compile(r"<!-- NEIGHBORHOODS:.*?<!-- /NEIGHBORHOODS -->\n", re.S)
DRAFT_SECTION_COUNT = 2
SHARED_FILES = ["styles.css", "site.js"]


def write_rankings_csv(scored: List[ScoredNeighborhood], path: Path) -> None:
    with open(path, "w", newline="") as f:
        writer = csv.writer(f)
        writer.writerow([
            "rank", "neighborhood", "priority", "readiness", "equity_flag",
            "infrastructure_age", "momentum", "grid_readiness", "equity_need",
            "gas_replacement_cost", "electrification_cost", "avoided_cost_ratio",
        ])
        for rank, s in enumerate(scored, start=1):
            writer.writerow([
                rank, s.neighborhood.name, round(s.priority, 3), round(s.readiness, 3),
                s.equity_flag,
                *(round(s.factors[k], 3) for k in
                  ("infrastructure_age", "momentum", "grid_readiness", "equity_need")),
                round(s.gas_replacement_cost), round(s.electrification_cost),
                round(s.avoided_cost_ratio, 2),
            ])


def _built_date() -> str:
    today = date.today()
    return f"{today:%B} {today.day}, {today.year}"


def write_data_js(path: Path) -> None:
    """Bundle the saved map data into one script (window.SNAPSHOTS).

    A script rather than separate .geojson files, because browsers block reading local data files
    when the page is opened straight from disk.
    """
    snapshots = {p.stem: json.loads(p.read_text()) for p in sorted(SNAPSHOTS.glob("*.geojson"))}
    if not snapshots:
        raise FileNotFoundError(f"No map data in {SNAPSHOTS}; run python3 scripts/fetch_data.py")
    snapshots["manifest"] = json.loads((SNAPSHOTS / "manifest.json").read_text())
    path.write_text("// Generated by run.py from data/snapshots/. Do not edit by hand.\n"
                    "window.SNAPSHOTS = " + json.dumps(snapshots, separators=(",", ":")) + ";\n")


def _copy_shared(dest: Path) -> None:
    dest.mkdir(parents=True, exist_ok=True)
    for name in SHARED_FILES:
        shutil.copyfile(WEB / name, dest / name)
    write_data_js(dest / "data.js")


def build_site(dest: Path) -> None:
    """Write the public page: statewide utility map and pilot map, without the draft neighborhood map."""
    html = (WEB / "index.html").read_text()
    html, count = DRAFT_SECTION.subn("", html)
    if count != DRAFT_SECTION_COUNT:
        raise ValueError(f"Expected {DRAFT_SECTION_COUNT} NEIGHBORHOODS sections in web/index.html, found {count}")
    _copy_shared(dest)
    (dest / "index.html").write_text(html.replace("__BUILT__", _built_date()))


def build_draft(scored: List[ScoredNeighborhood], dest: Path, sample_data: bool) -> None:
    """Write the full draft page (neighborhoods.html), including the neighborhood priority map."""
    rows = [
        {
            "rank": rank,
            "name": s.neighborhood.name,
            "lat": s.neighborhood.lat,
            "lon": s.neighborhood.lon,
            "units": s.neighborhood.housing_units,
            "priority": round(s.priority, 3),
            "readiness": round(s.readiness, 3),
            "equity": s.equity_flag,
            "factors": {k: round(v, 2) for k, v in s.factors.items()},
            "gasCost": s.gas_replacement_cost,
            "elecCost": s.electrification_cost,
            "ratio": round(s.avoided_cost_ratio, 2),
        }
        for rank, s in enumerate(scored, start=1)
    ]
    banner = (
        '<div class="banner">Sample data for demonstration only. '
        "Not real neighborhood figures.</div>" if sample_data else ""
    )
    _copy_shared(dest)
    shutil.copyfile(WEB / "neighborhoods.js", dest / "neighborhoods.js")
    (dest / "neighborhood-data.js").write_text(
        "// Generated by run.py: scored neighborhoods for the draft map.\nconst DATA = " + json.dumps(rows) + ";\n")
    html = (WEB / "index.html").read_text()
    (dest / "neighborhoods.html").write_text(html.replace("__BANNER__", banner).replace("__BUILT__", _built_date()))
